def svg(grid, cls=""):
    r = []
    for y, row in enumerate(grid):
        n = len(grid)
        x = 0
        while x < n:
            if row[x] == '#':
                w = 0
                while x + w < n and row[x + w] == '#':
                    w += 1
                r.append(f'<rect x="{x}" y="{y}" width="{w}" height="1.04"/>')
                x += w
            else:
                x += 1
    return (f'<svg class="osi {cls}" viewBox="0 0 {len(grid)} {len(grid)}" width="16" height="16" '
            f'aria-hidden="true" fill="currentColor" shape-rendering="crispEdges">' + ''.join(r) + '</svg>')


